def _space(st, w):
    from .model import GlyphOut, MONO_W
    adv = MONO_W if st.mono else round(w * getattr(st, 'spacef', 1.0) + st.sba)    # condensed cuts have a narrower word space
    return GlyphOut('space', [32], [], adv)


