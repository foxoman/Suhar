def svg_glyph(fname, height=CAP, sb=44):
    path = os.path.join(ROOT, 'third_party', 'currency-symbols', fname)
    rec = RecordingPen()
    for d in re.findall(r'<path[^>]* d="([^"]+)"', open(path, encoding='utf-8').read(), re.S):
        parse_path(d, rec)
    cs = E.from_recording(rec.value)
    bb = E.bounds(cs)
    s = height / (bb[3] - bb[1])
    cs = E.xform(cs, lambda x, y: ((x - bb[0]) * s, (bb[3] - y) * s))   # SVG y points down
    cs = E.union(cs)
    w = (bb[2] - bb[0]) * s

    def fn(st, d):
        c, ww, bear = cs, w, sb
        if st.mono:
            lim = MONO_W - 40
            if ww > lim:
                f = lim / ww
                c = E.xform(c, lambda x, y: (x * f, y * f + (height - height * f) / 2))
                ww = lim
            g = GlyphOut(d.name, d.uni, E.shift(c, (MONO_W - ww) / 2), MONO_W)
        else:
            g = GlyphOut(d.name, d.uni, E.shift(c, bear), round(ww + 2 * bear))
        g.needs_union = False
        return g
    return fn


