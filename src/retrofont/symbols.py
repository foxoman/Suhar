# ---- code ligatures for the Mono family (feature dlig) --------------------
def _lig(spec):
    def fn(st, d):
        if not st.mono:
            return None
        shapes = E.parse(spec, st.ns, lambda n: REG[n].spec)
        if st.italic:
            for sh in shapes:
                sh.transform(st.skew)
        g = GlyphOut(d.name, [], E.outline(shapes, st.pen), MONO_W)   # ink spans both cells: -600..600
        return g
    return fn


def _spacer(st, d):
    return GlyphOut(d.name, [], [], MONO_W) if st.mono else None


