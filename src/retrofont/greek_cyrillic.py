"""Greek (monotonic) and Cyrillic (Russian, Ukrainian, Belarusian, Bulgarian, Macedonian/Serbian
letters that decompose).  Letters that share a shape with Latin reuse its skeleton; lower-case
Cyrillic letters without a Latin twin are the capital skeleton refitted to the x-height (the pen is
not scaled, so they keep the lower-case weight)."""
from .model import G, REG, gname
from .latin import _BOWL_R
