def same(cp, src, **kw):
    d = REG[src if src in REG else gname(ord(src))]
    return G(cp, f"use:{d.name}", d.sb[0], d.sb[1], mono=(f"use:{d.name}" if not d.mono else d.mono), **kw)


def small(cp, cap, l=None, r=None, sx=0.8):
    d = REG[cap if cap in REG else ('uni%04X' % cap if isinstance(cap, int) else gname(ord(cap)))]
    return G(cp, f"use:{d.name}|{sx},X/C,0,0", (d.sb[0] if l is None else l) * 0.9, (d.sb[1] if r is None else r) * 0.9)


